-- PRIMARY KEY - Identifica cada registro (não repete e não fica vazia)
-- AUTO_INCREMENT - O próprio MySQL numera os registros
-- NOT NULL - O campo é obrigatório
-- UNIQUE - O valor não pode se repetir na tabela
-- DEFAULT - O valor usado quando ninguém informa nada
-- ENGINE=InnoDB; -  Responsável por gerenciar como os dados são lidos, gravados e protegidos no disco / (ACID) Garante atomicidade, consistência, isolamento e durabilidade, permitindo reverter operações (rollback) em caso de erro
-- FOREIGN KEY REFERENCES - Liga a viagem a um registro que já existe nas tabelas PK 
-- ON DELETE RESTRICT - Impede apagar linha, veículo ou motorista que tenha viagens (RN05)
-- NULL - Deixa o campo vazio: A viagem pode ainda não ter saído ou chegado
-- ON DELETE CASCADE faz o contrário do RESTRICT: se a viagem for apagada, os atrasos dela vão embora junto, porque um atraso sem viagem não faz sentido (RN06)
-- INSERT - cria um registro novo
-- UPDATE - muda um registro que já existe (o WHERE escolhe qual)
-- DELETE - apaga registros (o WHERE escolhe quais)
-- INNER JOIN  Junta tabelas pelas chaves (aqui, a linha com as suas viagens)
-- WHERE - Filtra as linhas que interessam
-- GROUP BY - Agrupa as linhas iguais (COUNT, SUM, AVG, MAX ou MIN)
-- COUNT conta quantas há em cada grupo
-- ORDER BY - Ordena o resultado (DESC = do maior para o menor)
-- Procedure - É uma rotina SQL guardada no banco; 
-- CALL executa a rotina pelo nome
-- IN - É um valor de entrada (um parâmetro) que a rotina recebe
-- DELIMITER - Troca o símbolo de fim de comando para o editor ler o bloco inteiro, (por isso o bloco termina com END$$ e depois volta para o ";")
-- COMMIT - confirma o bloco todo
-- ROLLBACK - desfaz tudo o que estava pendente
-- START TRANSACTION - abre um bloco: as alterações ficam pendentes
-- HANDLER - É o "plano B": se der qualquer erro, o MySQL executa este bloco
-- ROW_COUNT() - Diz quantas linhas o último comando alterou
-- SIGNAL - Cria um erro com a nossa mensagem
-- RESIGNAL - Mostra para quem chamou o erro que originou o ROLLBACK
-- O UPDATE só acerta a viagem se ela existe, está em andamento, ainda não tem -- atraso e os minutos são maiores que zero (RN07, RN08 e RN09)
-- Se o INSERT falhar (por exemplo, motivo inexistente), o ROLLBACK desfaz também o UPDATE (RN10)
--   Índice   é um "catálogo" que ajuda o MySQL a achar os registros sem ler a tabela toda
--   EXPLAIN  mostra o caminho que o MySQL escolheu para executar a consulta
--     type = ALL  o MySQL leu a tabela inteira (sem usar índice)
--     type = ref  o MySQL foi direto aos registros pelo índice
--     key         nome do índice usado (NULL = nenhum)
--     rows        quantidade estimada de linhas que o MySQL precisou examinar
--   CREATE USER  cria um usuário e define a senha
--   GRANT        concede permissões (quem pode fazer o quê)
--   REVOKE       retira permissões
-- O operador consulta, insere e atualiza, mas não exclui (RN11)
-- ACID neste projeto (para o relatório e a apresentação)
--   Atomicidade   registrar o atraso e marcar a viagem são um bloco só; se um passo
--                 falha, o ROLLBACK desfaz tudo (teste 9.4)
--   Consistência  o banco nunca fica com atraso sem viagem ou sem motivo válido,
--                 porque as chaves estrangeiras barram isso
--   Isolamento    enquanto a transação não é confirmada, outra conexão não enxerga
--                 a alteração pela metade
--   Durabilidade  depois do COMMIT (teste 3.2) o dado fica gravado, mesmo que o
--                 servidor seja reiniciado
